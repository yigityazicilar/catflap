import CatflapCore
import Foundation

/// Dolphin's right-click menu: `Send with Catflap ›` with one entry per paired device and
/// `Choose in Catflap…`, which opens the panel with the files attached. A KDE service menu in
/// the person's data folder; Plasma 6 runs only one that is executable. The agent rewrites it
/// whenever devices change. Device ids, not names, go into the commands.
enum ServiceMenu {
    static let fileName = "io.github.yigityazicilar.Catflap.desktop"

    static var directory: URL {
        let environment = ProcessInfo.processInfo.environment
        if let data = environment["XDG_DATA_HOME"], data.hasPrefix("/") {
            return URL(fileURLWithPath: data).appendingPathComponent("kio/servicemenus")
        }
        return FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent(".local/share/kio/servicemenus")
    }

    static var file: URL { directory.appendingPathComponent(fileName) }

    static func contents(devices: [DeviceSummary], executable: String) -> String {
        let program = DesktopEntry.quote(executable)
        // Ids are generated by Catflap; anything else is left out rather than quoted.
        let usable = devices.filter { device in
            !device.id.isEmpty && device.id.allSatisfy { $0.isLetter || $0.isNumber || $0 == "-" }
        }
        let names = usable.indices.map { "device\($0)" } + ["choose"]
        var text = """
        [Desktop Entry]
        Type=Service
        Name=Send with Catflap
        MimeType=all/allfiles;
        X-KDE-Submenu=Send with Catflap
        Icon=io.github.yigityazicilar.Catflap
        Actions=\(names.joined(separator: ";"));

        """
        for (index, device) in usable.enumerated() {
            // %f: Dolphin runs the command once per selected file.
            text += """

            [Desktop Action device\(index)]
            Name=\(DesktopEntry.name(device.name))
            Icon=computer
            Exec=\(program) send --to \(device.id) --file %f

            """
        }
        text += """

        [Desktop Action choose]
        Name=Choose in Catflap…
        Icon=io.github.yigityazicilar.Catflap
        Exec=\(program) ui invoke attach --file %f

        """
        return text
    }

    /// Writes the menu for these devices. A failure leaves the old menu; it is not worth
    /// stopping the agent for.
    static func write(devices: [DeviceSummary], executable: String) {
        do {
            try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
            let text = contents(devices: devices, executable: executable)
            if (try? String(contentsOf: file, encoding: .utf8)) != text {
                try text.write(to: file, atomically: true, encoding: .utf8)
            }
            try FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: file.path)
        } catch {}
    }
}
