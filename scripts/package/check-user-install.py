#!/usr/bin/env python3
"""Exercise the per-user installer without touching the session or user data."""
import os
from pathlib import Path
import subprocess
import tempfile

root = Path(__file__).resolve().parents[2]
binary = Path(subprocess.check_output(['swift', 'build', '--show-bin-path'], cwd=root, text=True).strip()) / 'catflap'
with tempfile.TemporaryDirectory(prefix='catflap-user-install-') as temporary:
    home = Path(temporary)
    prefix = home / '.local'
    env = dict(os.environ, HOME=str(home), XDG_CONFIG_HOME=str(home / '.config'), XDG_DATA_HOME=str(prefix / 'share'))
    for key in ('DISPLAY', 'WAYLAND_DISPLAY', 'WAYLAND_SOCKET', 'DBUS_SESSION_BUS_ADDRESS'):
        env.pop(key, None)
    subprocess.run(['bash', str(root / 'packaging/linux/install.sh'), '--binary', str(binary)], env=env, check=True)
    files = sorted(str(p.relative_to(home)) for p in home.rglob('*') if p.is_file() or p.is_symlink())
    print('INSTALLED', files, flush=True)
    assert '.local/bin/catflap' in files
    assert '.config/autostart/io.github.yigityazicilar.Catflap.desktop' in files
    subprocess.run(['bash', str(root / 'packaging/linux/install.sh'), '--uninstall'], env=env, check=True)
    # Shared desktop/icon caches are generated by system tools, not Catflap payload.
    caches = {'.local/share/applications/mimeinfo.cache', '.local/share/icons/hicolor/icon-theme.cache'}
    remaining = [str(p.relative_to(home)) for p in home.rglob('*') if (p.is_file() or p.is_symlink()) and str(p.relative_to(home)) not in caches]
    assert not remaining, remaining
    print('UNINSTALLED: no installed files remain', flush=True)
